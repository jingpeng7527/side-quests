#!/usr/bin/env node
// Measures the display font's glyph widths in headless Chrome and writes
// app/src/ui/fontMetrics.ts, so the app can size text to fit exactly (on every
// platform — adjustsFontSizeToFit doesn't exist on the web).
//   node scripts/measure-font.mjs
import { spawn } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontFile = pathToFileURL(join(root, "node_modules/@expo-google-fonts/big-shoulders-display/BigShouldersDisplay_900Black.ttf")).href;
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?'’\"“”-–—&()/#%+…";
// A file:// page, so it may load the local font file.
const pageFile = join(mkdtempSync(join(tmpdir(), "font-page-")), "measure.html");
writeFileSync(pageFile, "<!doctype html><body>");
const page = pathToFileURL(pageFile).href;

const chrome = spawn("/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", ["--headless=new", "--remote-debugging-port=9338", "--allow-file-access-from-files", "--no-first-run", `--user-data-dir=${mkdtempSync(join(tmpdir(), "font-"))}`, "about:blank"], { stdio: "ignore" });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let t;
for (let i = 0; i < 50 && !t; i++) try { t = await (await fetch("http://127.0.0.1:9338/json")).json(); } catch { await sleep(200); }
const ws = new WebSocket(t.find((x) => x.type === "page").webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Page.navigate", { url: page });
await sleep(800);
const expr = `(async () => {
  const f = new FontFace("M", "url('${fontFile}')"); await f.load(); document.fonts.add(f);
  const c = document.createElement("canvas").getContext("2d"); c.font = "1000px M";
  const out = {}; for (const ch of ${JSON.stringify(chars)}) out[ch] = Math.round(c.measureText(ch).width) / 1000;
  return out;
})()`;
const r = await send("Runtime.evaluate", { expression: expr, awaitPromise: true, returnByValue: true });
if (!r.result?.value) {
  console.error("measuring failed:", JSON.stringify(r).slice(0, 400));
  chrome.kill();
  process.exit(1);
}
ws.close(); chrome.kill();
const widths = r.result.value;
const file = `// Generated by scripts/measure-font.mjs — Big Shoulders Display Black glyph advance widths, in em.
export const DISPLAY_WIDTHS: Record<string, number> = ${JSON.stringify(widths, null, 0).replace(/,"/g, ', "')};

/** Width of anything not listed (wide-ish, to err on the side of fitting). */
export const DISPLAY_FALLBACK = ${Math.max(...Object.values(widths)).toFixed(3)};
`;
writeFileSync(join(root, "app/src/ui/fontMetrics.ts"), file);
console.log(`measured ${Object.keys(widths).length} glyphs: W=${widths.W}em I=${widths.I}em space=${widths[" "]}em`);
process.exit(0);
